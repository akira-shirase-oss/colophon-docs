#!/usr/bin/env node
// After the build: every page's Markdown copy (/quick-start.md, /api/delivery.md, …) names its HTML
// page as canonical with an HTTP Link header, so search engines index the page, not the copy, and
// the copy stays in the output for readers and tools (llms.txt points at the copies).
// Appends one rule per copy to dist/_headers, and fails if the file would pass Cloudflare Pages'
// limit of 100 rules (https://developers.cloudflare.com/pages/configuration/headers/).
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { canonicalRules, countRules, MAX_RULES } from './lib/headers.mjs';

const dist = new URL('../dist/', import.meta.url).pathname;
const site = 'https://docs.colophon.404human.dev';

const copies = [];
(function walk(dir) {
	for (const name of readdirSync(dir)) {
		const path = join(dir, name);
		if (statSync(path).isDirectory()) walk(path);
		else if (path.endsWith('.md')) copies.push('/' + relative(dist, path));
	}
})(dist);

const headersPath = join(dist, '_headers');
const headers = readFileSync(headersPath, 'utf8');
const rules = canonicalRules(site, copies);
const written = `${headers.trimEnd()}\n\n# Generated by scripts/md-canonical.mjs: each Markdown copy names its page as canonical.\n${rules}`;
const count = countRules(written);
if (count > MAX_RULES) {
	console.error(`md-canonical: dist/_headers would have ${count} rules; Cloudflare Pages allows ${MAX_RULES}`);
	process.exit(1);
}
writeFileSync(headersPath, written);
console.log(`md-canonical: ${copies.length} Markdown copies name their page as canonical; dist/_headers has ${count} of ${MAX_RULES} rules`);
